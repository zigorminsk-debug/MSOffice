def build_help_text() -> str:
    parts = ["КАК ПОЛЬЗОВАТЬСЯ ПРОГРАММОЙ"]
    for number, section in enumerate(FEATURE_SECTIONS, 1):
        parts.extend(["", f"{number}. {section['title'].upper()}", ""])
        parts.extend(section["paragraphs"])
        parts.extend(f"• {item}" for item in section["items"])
    return "\n".join(parts)


HELP_TEXT = build_help_text()
